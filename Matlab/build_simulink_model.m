function out = build_simulink_model(R, opt)
% BUILD_SIMULINK_MODEL  Builds, saves and opens acoustic_pursuit_loop.slx (needs MATLAB + Simulink).
%
%   build_simulink_model();                                   % runs acoustic_pursuit_design with defaults, then builds the model
%   R = acoustic_pursuit_design(struct('controller','place')); build_simulink_model(R);
%   build_simulink_model(R, struct('validate', true));        % also simulates it and compares with the reference simulation
%
% WHAT THE MODEL IS (it mirrors the control-loop block diagram of the report)
%   Plant (blue)      : nonlinear relative kinematics (Integrator + MATLAB Function) with first-order actuator lags (State-Space)
%   Sensor            : paired acoustic measurement (Eqs. amp, beta, rho) sampled every Tm, A- taken Tdw earlier, Rician noise,
%                       validity flag, sample counter; then Transport Delay Td
%   Observer (orange) : discrete observer on [d_rho beta eps dv_t w_t] at Ts; a new valid sample (counter changed) corrects the estimate by
%                       Phi(Td)*L*(y - C*xhat(t-Td)), where xhat(t-Td) comes from a Transport Delay of the observer's own output
%   Controller        : state feedback + integral action + command limits (same code as acoustic_pursuit_design.m)
% All gains come from R.D, all parameters from R.P (they are stored in the model workspace, so the .slx is self-contained).
% Supported: observer with disturbance states (5 states), 'kalman' or 'luenberger'; any controller type except none.
%
% ROBUSTNESS LAYER (same as acoustic_pursuit_design.m): soft innovation gate (clipping near lock) in the observer block (S, chi2 limit and
%   lock zone are appended to Po), watchdog / hard stop in the controller block (the observer's 2nd output is the number of Ts steps since the last
%   accepted sample), optional reflections in the sensor block (Ps(8:9)). NOT in the Simulink model: period jitter, dropped captures and
%   outage windows (P.Tm_jitter, P.p_drop, P.outage): those exist only in the reference simulation R.simulate.
%
% SAFETY NET: every block and connection is registered; the script stops with a clear message if a port does not exist, an input is
% driven twice, or an input is left unconnected. The block code is the same as the tested reference simulation.
% VALIDATION: build_simulink_model(R, struct('validate',true)) runs the model with measurement noise off and prints the maximum
% difference to R.simulate (reference): a few centimetres / degrees is expected (continuous actuators vs held inputs).

if nargin >= 1 && ischar(R) && strcmp(R, 'code'), out = fcn_code();  return; end
if isempty(ver('simulink')) || ~license('test', 'Simulink')
    error('build_simulink_model:noSimulink', ['Simulink is not installed or not licensed (needed for bdIsLoaded, new_system, ...).\n' ...
          'Install it (Home > Add-Ons > Get Add-Ons) or use R.simulate, the reference simulation, which needs only base MATLAB.']);
end
if nargin < 1 || isempty(R)
    evalc("R = acoustic_pursuit_design(struct('run_mc',false,'run_S1',false,'plot',false,'export',false));");
end
if nargin < 2, opt = struct(); end
mdl = 'acoustic_pursuit_loop';  if isfield(opt,'name'), mdl = opt.name; end
doval = isfield(opt,'validate') && opt.validate;
D = R.D;  P = R.P;
if D.nx ~= 5 || D.ideal, error('The Simulink model needs an observer with disturbance states (observer ''kalman'' or ''luenberger'', dist_states true).'); end

%% parameter vectors (same layout as the block code below)
Po = [D.Phi(:); D.Gam(:); D.Co(:); D.L(:); D.PhiTd(:); D.S(:); min(D.gate_chi2,1e9); D.gate_zone(:)];   % 25+10+10+10+25 + 4 + 3 = 87
Pc = [reshape(D.Kd(:,1:3),[],1); D.Kd(:,4); D.Ad4(:); D.Bd4(:); ...                  % Kx(6) Kz(2) Ad4(3) Bd4(2)
      P.v0; P.v_max; P.ds_max; P.L; P.zmax; P.phi_max; P.zband; double(D.integral); ...   % + 8 scalars = 21
      P.Ts; P.t_lost; P.rho_stop; P.d];                                                % + watchdog (Ts, t_lost, rho_stop, d*) = 25
Ps = [P.K; P.Kerr; P.sig; P.dlt; P.sn; P.A_thr; P.d; P.refl_p; P.refl_g];              % 9
assert(numel(Po) == 87 && numel(Pc) == 25 && numel(Ps) == 9, 'parameter vector sizes changed');
code = fcn_code();

%% create the model
if bdIsLoaded(mdl), close_system(mdl, 0); end
if exist([mdl '.slx'], 'file') == 2, delete([mdl '.slx']); end
new_system(mdl);
h = P.Ts/5;
for v = [P.Ts P.Tm P.Td P.Tdw]
    if abs(v/h - round(v/h)) > 1e-9, warning('Ts, Tm, Td, Tdw should be multiples of the solver step %.4g s', h); end
end
set_param(mdl, 'SolverType','Fixed-step', 'Solver','ode4', 'FixedStep',num2str(h), 'StopTime',num2str(P.T));

mw = get_param(mdl, 'ModelWorkspace');
vars = {'Po',Po; 'Pc',Pc; 'Ps',Ps; 'x0',P.x0_demo(:); 'wt',[P.v0 + P.dvt_demo; 0]; 'Ts',P.Ts; 'Tm',P.Tm; 'Td',P.Td; 'Tdw',P.Tdw; ...
        'v0',P.v0; 'tau_v',P.tau_v; 'tau_w',P.tau_w};
for i = 1:size(vars,1), mw.assignin(vars{i,1}, vars{i,2}); end

L_ = struct('int','simulink/Continuous/Integrator', 'const','simulink/Sources/Constant', 'ss','simulink/Continuous/State-Space', ...
            'zoh','simulink/Discrete/Zero-Order Hold', 'ud','simulink/Discrete/Unit Delay', ...
            'td','simulink/Continuous/Transport Delay', 'mux','simulink/Signal Routing/Mux', 'dmx','simulink/Signal Routing/Demux', ...
            'ws','simulink/Sinks/To Workspace', 'fcn','simulink/User-Defined Functions/MATLAB Function');
reg = struct('nin',struct(), 'nout',struct(), 'driven',struct());
%                 name        library   in out col row  parameters ...
reg = add_blk(reg, mdl, 'Wt',        L_.const, 0, 1, 0, 0, 'Value','wt');
reg = add_blk(reg, mdl, 'ActV',      L_.ss,    1, 1, 0, 1, 'A','-1/tau_v', 'B','1/tau_v', 'C','1', 'D','0', 'X0','v0');
reg = add_blk(reg, mdl, 'ActW',      L_.ss,    1, 1, 0, 2, 'A','-1/tau_w', 'B','1/tau_w', 'C','1', 'D','0', 'X0','0');
reg = add_blk(reg, mdl, 'plant',     L_.fcn,   4, 1, 1, 1);
reg = add_blk(reg, mdl, 'Integrator',L_.int,   1, 1, 2, 1, 'InitialCondition','x0');
reg = add_blk(reg, mdl, 'LogX',      L_.ws,    1, 0, 3, 0, 'VariableName','Xsim', 'SaveFormat','Array', 'SampleTime','-1');
reg = add_blk(reg, mdl, 'Zx',        L_.zoh,   1, 1, 3, 2, 'SampleTime','Tm');
reg = add_blk(reg, mdl, 'Dw',        L_.td,    1, 1, 3, 3, 'DelayTime','Tdw', 'InitialOutput','x0', 'BufferSize','1024');
reg = add_blk(reg, mdl, 'Zxd',       L_.zoh,   1, 1, 4, 3, 'SampleTime','Tm');
reg = add_blk(reg, mdl, 'Zphi',      L_.zoh,   1, 1, 4, 4, 'SampleTime','Tm');
reg = add_blk(reg, mdl, 'PsConst',   L_.const, 0, 1, 4, 5, 'Value','Ps');
reg = add_blk(reg, mdl, 'sens',      L_.fcn,   4, 3, 5, 3);
reg = add_blk(reg, mdl, 'MuxS',      L_.mux,   3, 1, 6, 3, 'Inputs','3');
reg = add_blk(reg, mdl, 'DelS',      L_.td,    1, 1, 7, 3, 'DelayTime','Td', 'InitialOutput','zeros(4,1)', 'BufferSize','1024');
reg = add_blk(reg, mdl, 'DemS',      L_.dmx,   1, 3, 8, 3, 'Outputs','[2 1 1]');
reg = add_blk(reg, mdl, 'Zym',       L_.zoh,   1, 1, 9, 2, 'SampleTime','Ts');
reg = add_blk(reg, mdl, 'Zvl',       L_.zoh,   1, 1, 9, 3, 'SampleTime','Ts');
reg = add_blk(reg, mdl, 'Zcn',       L_.zoh,   1, 1, 9, 4, 'SampleTime','Ts');
reg = add_blk(reg, mdl, 'obs',       L_.fcn,   6, 2, 10, 3);
reg = add_blk(reg, mdl, 'PoConst',   L_.const, 0, 1, 10, 5, 'Value','Po');
reg = add_blk(reg, mdl, 'DelX',      L_.td,    1, 1, 11, 4, 'DelayTime','Td', 'InitialOutput','zeros(5,1)', 'BufferSize','1024');
reg = add_blk(reg, mdl, 'Zxhd',      L_.zoh,   1, 1, 12, 4, 'SampleTime','Ts');
reg = add_blk(reg, mdl, 'LogXH',     L_.ws,    1, 0, 11, 2, 'VariableName','XHsim', 'SaveFormat','Array', 'SampleTime','-1');
reg = add_blk(reg, mdl, 'ZxhC',      L_.zoh,   1, 1, 11, 1, 'SampleTime','Ts');
reg = add_blk(reg, mdl, 'ZageC',     L_.zoh,   1, 1, 11, 0, 'SampleTime','Ts');
reg = add_blk(reg, mdl, 'ctrl',      L_.fcn,   3, 4, 12, 1);
reg = add_blk(reg, mdl, 'PcConst',   L_.const, 0, 1, 12, 0, 'Value','Pc');
reg = add_blk(reg, mdl, 'UD',        L_.ud,    1, 1, 10, 1, 'InitialCondition','[0;0]', 'SampleTime','Ts');

names = fieldnames(code);
for i = 1:numel(names), set_fcn_code([mdl '/' names{i}], code.(names{i})); end

%% wiring (source, source port, destination, destination port)
W = {'Wt',1,'plant',4;  'ActV',1,'plant',2;  'ActW',1,'plant',3;  'Integrator',1,'plant',1;  'plant',1,'Integrator',1;
     'Integrator',1,'LogX',1;
     'Integrator',1,'Zx',1;  'Zx',1,'sens',1;  'Integrator',1,'Dw',1;  'Dw',1,'Zxd',1;  'Zxd',1,'sens',2;
     'Zphi',1,'sens',3;  'PsConst',1,'sens',4;
     'sens',1,'MuxS',1;  'sens',2,'MuxS',2;  'sens',3,'MuxS',3;  'MuxS',1,'DelS',1;  'DelS',1,'DemS',1;
     'DemS',1,'Zym',1;  'DemS',2,'Zvl',1;  'DemS',3,'Zcn',1;
     'Zym',1,'obs',2;  'Zvl',1,'obs',3;  'Zcn',1,'obs',4;  'UD',1,'obs',1;  'PoConst',1,'obs',6;
     'obs',1,'DelX',1;  'DelX',1,'Zxhd',1;  'Zxhd',1,'obs',5;  'obs',1,'LogXH',1;
     'obs',1,'ZxhC',1;  'ZxhC',1,'ctrl',1;  'PcConst',1,'ctrl',2;  'obs',2,'ZageC',1;  'ZageC',1,'ctrl',3;
     'ctrl',1,'ActV',1;  'ctrl',2,'ActW',1;  'ctrl',3,'UD',1;  'ctrl',4,'Zphi',1};
for i = 1:size(W,1), reg = connect(reg, mdl, W{i,1}, W{i,2}, W{i,3}, W{i,4}); end
fn = fieldnames(reg.driven);
for i = 1:numel(fn)
    open_ports = find(reg.driven.(fn{i}) == 0);
    if ~isempty(open_ports), error('Block %s has unconnected input port(s) %s', fn{i}, mat2str(open_ports)); end
end
fprintf('built %s: %d blocks, %d connections, all input ports driven exactly once\n', mdl, numel(fieldnames(reg.nin)), size(W,1));

save_system(mdl, [mdl '.slx']);
if ~isfield(opt,'open') || opt.open, open_system(mdl); end
if doval, validate_model(R, mdl, mw, Ps); end
out = mdl;
end

%% =====================================================================================================================
%% helpers
%% =====================================================================================================================
function reg = add_blk(reg, mdl, name, lib, nin, nout, col, row, varargin)
pos = [40 + col*170, 40 + row*90, 40 + col*170 + 110, 40 + row*90 + 55];
add_block(lib, [mdl '/' name], 'Position', pos, varargin{:});
reg.nin.(name) = nin;  reg.nout.(name) = nout;  reg.driven.(name) = zeros(1, nin);
end

function reg = connect(reg, mdl, src, sp, dst, dp)
if ~isfield(reg.nout, src) || sp > reg.nout.(src), error('connect: block %s has no output port %d', src, sp); end
if ~isfield(reg.nin, dst) || dp > reg.nin.(dst),   error('connect: block %s has no input port %d', dst, dp); end
if reg.driven.(dst)(dp) ~= 0, error('connect: input %d of %s is already driven', dp, dst); end
reg.driven.(dst)(dp) = 1;
add_line(mdl, sprintf('%s/%d', src, sp), sprintf('%s/%d', dst, dp), 'autorouting', 'on');
end

function set_fcn_code(path, code)
rt = sfroot;
ch = rt.find('-isa', 'Stateflow.EMChart', 'Path', path);
ch.Script = code;
end

function validate_model(R, mdl, mw, Ps)
P = R.P;
ps0 = Ps;  ps0([5 8]) = 0;                                % measurement noise and reflections off, so the comparison is deterministic
mw.assignin('Ps', ps0);
so = sim(mdl, 'StopTime', num2str(P.T), 'ReturnWorkspaceOutputs', 'on');
mw.assignin('Ps', Ps);
X = so.get('Xsim');  t = so.get('tout');
wt = [P.v0 + P.dvt_demo; 0];
ref = R.simulate(P.x0_demo, @(tt) wt, P.T, 0);
Xr = interp1(ref.t(:), ref.X.', t(:));
err = max(abs(X - Xr), [], 1);
fprintf('Simulink vs reference simulation (noise off): max |difference| = %.3f m (range), %.2f deg (bearing), %.2f deg (heading)\n', ...
        err(1), err(2)*180/pi, err(3)*180/pi);
if err(1) < 0.05 && all(err(2:3) < 0.05), fprintf('  -> consistent: wiring and sample times behave as designed.\n');
else, fprintf('  -> LARGE difference: check sample times, delays and wiring (compare Xsim with R.simulate trace).\n'); end
end

%% =====================================================================================================================
%% block code (MATLAB Function blocks). Same logic as the subfunctions of acoustic_pursuit_design.m.
%% =====================================================================================================================
function c = fcn_code()
c.plant = strjoin({ ...
'function xdot = plant(x, vf, wf, w)', ...
'x = x(:); w = w(:);', ...
'rho = max(x(1), 1e-2); beta = x(2); al = x(3) - beta;', ...
'xdot = [ w(1)*cos(al) - vf*cos(beta); ...', ...
'        (w(1)*sin(al) + vf*sin(beta))/rho - wf; ...', ...
'         w(2) - wf ];'}, char(10));
c.sens = strjoin({ ...
'function [y, valid, cnt] = sens(x, xd, phic, Ps)', ...
'persistent n', ...
'if isempty(n), n = 0; end', ...
'x = x(:); xd = xd(:); Ps = Ps(:);', ...
'K = Ps(1); Kerr = Ps(2); sig = Ps(3); dlt = Ps(4); sn = Ps(5); Athr = Ps(6); d = Ps(7); rp = Ps(8); rg = Ps(9);', ...
'Am = amp_(K*Kerr, xd(1), xd(2), phic - dlt, sig, sn, rp, rg);', ...
'Ap = amp_(K*Kerr, x(1),  x(2),  phic + dlt, sig, sn, rp, rg);', ...
'b = phic + sig^2/(2*dlt)*log(Ap/Am);', ...
'r = K/sqrt(Ap*Am)*exp(-((phic - b)^2 + dlt^2)/(2*sig^2));', ...
'y = [r - d; b];', ...
'valid = double(min(Am, Ap) > Athr);', ...
'n = n + 1;', ...
'cnt = n;', ...
'', ...
'function A = amp_(Kt, rho, beta, phi, sig, sn, rp, rg)', ...
'a0 = Kt/max(rho, 1e-2)*exp(-(phi - beta)^2/(2*sig^2));', ...
'ec = complex(0,0);', ...
'if rp > 0 && rand < rp, ec = rg*a0*exp(1j*2*pi*rand); end', ...
'A = abs(complex(a0 + sn*randn, sn*randn) + ec);'}, char(10));
c.obs = strjoin({ ...
'function [xh, age] = obs(uprev, ym, valid, cnt, xhd, Po)', ...
'persistent x cprev init age_', ...
'if isempty(x), x = zeros(5,1); cprev = 0; init = false; age_ = 0; end', ...
'uprev = uprev(:); ym = ym(:); xhd = xhd(:); Po = Po(:);', ...
'Phi = reshape(Po(1:25),5,5); Gam = reshape(Po(26:35),5,2); Co = reshape(Po(36:45),2,5);', ...
'L = reshape(Po(46:55),5,2); PhiTd = reshape(Po(56:80),5,5);', ...
'S = reshape(Po(81:84),2,2); chi2 = Po(85); zr = Po(86); zb = Po(87);', ...
'x = Phi*x + Gam*uprev;', ...
'age_ = age_ + 1;', ...
'cn = round(cnt);', ...
'if abs(cnt - cn) < 1e-6 && cn ~= cprev          % clean sample only (Transport Delay may interpolate at edges)', ...
'    cprev = cn;', ...
'    if valid > 0.5', ...
'        if ~init', ...
'            x = PhiTd*[ym; 0; 0; 0];', ...
'            init = true;  age_ = 0;', ...
'        else', ...
'            nu = ym - Co*xhd;', ...
'            d2 = nu''*(S\nu);', ...
'            if abs(x(1)) < zr && abs(x(2)) < zb && d2 > chi2      % soft gate: clip the innovation, near lock only', ...
'                nu = nu*sqrt(chi2/d2);', ...
'            end', ...
'            x = x + PhiTd*(L*nu);  age_ = 0;', ...
'        end', ...
'    end', ...
'end', ...
'xh = x;', ...
'age = age_;'}, char(10));
c.ctrl = strjoin({ ...
'function [vcmd, wcmd, ua, phic] = ctrl(xh, Pc, age)', ...
'persistent z', ...
'if isempty(z), z = 0; end', ...
'xh = xh(:); Pc = Pc(:);', ...
'Kx = reshape(Pc(1:6),2,3); Kz = Pc(7:8); Ad4 = Pc(9:11).''; Bd4 = Pc(12:13).'';', ...
'v0 = Pc(14); vmax = Pc(15); dsmax = Pc(16); Lw = Pc(17); zmax = Pc(18); phimax = Pc(19); zband = Pc(20); integ = Pc(21);', ...
'Ts = Pc(22); tlost = Pc(23); rstop = Pc(24); dstar = Pc(25);', ...
'stopped = (age*Ts > tlost) || (xh(1) + dstar < rstop);      % hard stop (watchdog)', ...
'u = -Kx*xh(1:3) - Kz*z;', ...
'vcmd = min(max(v0 + u(1), 0), vmax);', ...
'if stopped, vcmd = 0; end', ...
'wlim = max(vcmd, 0.05)*tan(dsmax)/Lw;', ...
'wcmd = min(max(u(2), -wlim), wlim);', ...
'if stopped, wcmd = 0; end', ...
'ua = [vcmd - v0; wcmd];', ...
'if integ > 0.5 && ~stopped && vcmd == v0 + u(1) && abs(xh(1)) < zband', ...
'    z = min(max(Ad4*xh(1:3) + z + Bd4*ua, -zmax), zmax);', ...
'end', ...
'phic = min(max(xh(2), -phimax), phimax);'}, char(10));
end
